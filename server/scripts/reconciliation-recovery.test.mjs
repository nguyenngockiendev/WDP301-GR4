import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createHmac } from 'node:crypto';
import mongoose from 'mongoose';
import { MongoMemoryReplSet } from 'mongodb-memory-server';
import Users from '../src/models/Users.js';
import Properties from '../src/models/Properties.js';
import Rooms from '../src/models/Rooms.js';
import Contracts from '../src/models/Contracts.js';
import ManagerAssignments from '../src/models/ManagerAssignments.js';
import Invoices from '../src/models/Invoices.js';
import Payments from '../src/models/Payments.js';
import Notifications from '../src/models/Notifications.js';
import GatewayEvents from '../src/models/GatewayEvents.js';
import { getReconciliation, syncPayment } from '../src/modules/reconciliation/reconciliation.service.js';

test('manager recovery verifies evidence, scope and amounts; concurrent retries credit once', async () => {
 const db = await MongoMemoryReplSet.create({ replSet: { count: 1 } });
 try {
  await mongoose.connect(db.getUri());
  process.env.VNP_TMNCODE='TESTCODE'; process.env.VNP_HASH_SECRET='test-only-key';
  const [owner,manager,outsider,tenant] = await Users.create(['landlord','manager','manager','tenant'].map((role,i)=>({username:`recover${i}`,email:`recover${i}@test.local`,fullName:`User ${i}`,role})));
  const property=await Properties.create({owner:owner.id,name:'Demo',address:'Test'});
  const room=await Rooms.create({property:property.id,roomNumber:'101',area:20,price:100000});
  const contract=await Contracts.create({room:room.id,representative:tenant.id,startDate:new Date(),endDate:new Date(Date.now()+86400000),monthlyRent:100000,createdBy:owner.id});
  await ManagerAssignments.create({manager:manager.id,property:property.id,assignedBy:owner.id});
  const invoice=await Invoices.create({contract:contract.id,billingMonth:'2026-11',totalAmount:100000,dueDate:new Date(),createdBy:owner.id});
  const payment=await Payments.create({invoice:invoice.id,payer:tenant.id,method:'gateway',provider:'vnpay',amount:100000,status:'failed',expiresAt:new Date(),paidAt:null});
  await assert.rejects(syncPayment(payment.id,tenant.id),e=>e.status===403);
  await assert.rejects(syncPayment(payment.id,outsider.id),e=>e.status===403);
  await assert.rejects(syncPayment(payment.id,manager.id),e=>e.status===409);
  const raw={vnp_TxnRef:payment.id,vnp_TmnCode:'TESTCODE',vnp_Amount:'10000000',vnp_ResponseCode:'00',vnp_TransactionStatus:'00',vnp_TransactionNo:'123456',vnp_PayDate:'20261110130000'};
  const sign=()=> { const encoded=new URLSearchParams(Object.entries(raw).filter(([key])=>key!=='vnp_SecureHash').sort(([a],[b])=>a.localeCompare(b))).toString(); raw.vnp_SecureHash=createHmac('sha512','test-only-key').update(encoded).digest('hex'); };
  sign();
  const event=await GatewayEvents.create({source:'RETURN',txnRef:payment.id,amount:100000,signatureValid:true,responseCode:'00',transactionStatus:'00',raw:{...raw,vnp_SecureHash:'0'.repeat(128)},processResult:'ERROR'});
  await assert.rejects(syncPayment(payment.id,manager.id),e=>e.status===409);
  raw.vnp_Amount='9000000';sign(); await GatewayEvents.updateOne({_id:event.id},{raw});
  await assert.rejects(syncPayment(payment.id,manager.id),e=>e.status===409);
  raw.vnp_Amount='10000000';sign();await GatewayEvents.updateOne({_id:event.id},{raw});
  await Invoices.updateOne({_id:invoice.id},{paidAmount:1});
  await assert.rejects(syncPayment(payment.id,manager.id),e=>e.status===409);
  await Invoices.updateOne({_id:invoice.id},{paidAmount:0,status:'cancelled'});
  await assert.rejects(syncPayment(payment.id,manager.id),e=>e.status===409);
  await Invoices.updateOne({_id:invoice.id},{status:'unpaid'});
  const before=await getReconciliation(manager.id,{month:'2026-11'});
  assert.equal(before.items[0].recoveryActions.length,1);
  assert.equal('gatewayEvents' in before.items[0],false);
  assert.equal(JSON.stringify(before).includes('signatureValid'),false);
  await Promise.all([syncPayment(payment.id,manager.id),syncPayment(payment.id,manager.id)]);
  assert.equal((await Invoices.findById(invoice.id)).paidAmount,100000);
  assert.equal((await Payments.findById(payment.id)).recordedBy.toString(),manager.id);
  assert.equal(await Notifications.countDocuments({eventKey:`payment-success:${payment.id}`}),2);
  await syncPayment(payment.id,manager.id);
  const after=await getReconciliation(manager.id,{month:'2026-11'});
  assert.equal(after.items[0].recoveryActions.length,0);
  assert.equal(after.summary.review,0);
  await ManagerAssignments.updateMany({manager:manager.id},{status:'inactive'});
  await assert.rejects(syncPayment(payment.id,manager.id),e=>e.status===403);
 } finally { await mongoose.disconnect();await db.stop(); }
});
