import Contracts from '../../models/Contracts.js';
import Rooms from '../../models/Rooms.js';
import ManagerAssignments from '../../models/ManagerAssignments.js';
import TerminationRequests from '../../models/TerminationRequests.js';
import { createNotification } from '../notifications/notifications.service.js';

const CHECK_INTERVAL_MS = 60 * 60 * 1000; // Kiểm tra mỗi giờ

/**
 * Tạo checkout request tự động cho hợp đồng đã đến ngày hết hạn.
 * Không kết thúc Contract và không thay đổi trạng thái Room tại đây.
 */
export const processExpiredContracts = async () => {
  const now = new Date();
  const expiredContracts = await Contracts.find({
    status: 'active',
    endDate: { $lte: now },
  }).select('_id room representative otherMembers endDate');

  let createdCount = 0;

  for (const contract of expiredContracts) {
    try {
      // Nếu đã có request đang xử lý thì không tạo request thứ hai.
      const existingActiveRequest = await TerminationRequests.exists({
        contract: contract._id,
        status: { $in: ['pending', 'approved'] },
      });
      if (existingActiveRequest) continue;

      // Kiểm tra khóa riêng để job chạy lại không tạo trùng request tự động.
      const existingAutoRequest = await TerminationRequests.exists({
        autoGeneratedForContract: contract._id,
      });
      if (existingAutoRequest) continue;

      const room = await Rooms.findById(contract.room).select('_id property roomNumber');
      if (!room) {
        console.warn(`[CheckoutExpiry] Không tìm thấy phòng của Contract ${contract._id}`);
        continue;
      }

      const request = await TerminationRequests.create({
        contract: contract._id,
        requestedBy: contract.representative,
        source: 'system',
        autoGeneratedForContract: contract._id,
        requestedDate: now,
        moveOutDate: contract.endDate,
        reason: 'Hợp đồng đã đến ngày hết hạn. Hệ thống tự động tạo yêu cầu trả phòng để Manager xử lý.',
        status: 'pending',
      });

      createdCount += 1;

      const managerAssignment = await ManagerAssignments.findOne({
        property: room.property,
        status: 'active',
      }).select('manager');

      // Checkout request được gắn với người đại diện hợp đồng (requestedBy),
      // vì vậy chỉ gửi thông báo cho người đại diện để họ mở được request trong mục của mình.
      const tenantIds = [contract.representative].filter(Boolean);

      const recipients = [...new Set([
        ...tenantIds.map(String),
        ...(managerAssignment?.manager ? [String(managerAssignment.manager)] : []),
      ])];

      const tenantContent =
        `Hợp đồng thuê phòng ${room.roomNumber} của bạn đã đến ngày hết hạn. ` +
        'Hệ thống đã tự tạo yêu cầu trả phòng. Vui lòng phối hợp với Manager để kiểm tra tài sản, đối soát công nợ và hoàn tất checkout.';

      const managerContent =
        `Hợp đồng tại phòng ${room.roomNumber} đã đến hạn. ` +
        'Hệ thống đã tự tạo checkout request. Vui lòng mở yêu cầu để kiểm tra tài sản, đối soát và xử lý checkout.';

      await Promise.all(recipients.map(recipient =>
        createNotification({
          recipient,
          ...(managerAssignment?.manager && recipient === String(managerAssignment.manager)
            ? {
                title: 'Hợp đồng đến hạn - cần xử lý checkout',
                content: managerContent,
              }
            : {
                title: 'Hợp đồng đã đến hạn - yêu cầu trả phòng',
                content: tenantContent,
              }),
          type: 'checkout_due',
          related: { entityType: 'TerminationRequest', entityId: request._id },
          property: room.property,
        })
      ));
    } catch (error) {
      // E11000 có thể xảy ra nếu hai tiến trình cùng tạo request cho một hợp đồng.
      if (error?.code === 11000) continue;
      console.error(
        `[CheckoutExpiry] Không xử lý được Contract ${contract._id}:`,
        error.message,
      );
    }
  }

  if (createdCount) {
    console.log(`[CheckoutExpiry] Đã tự tạo ${createdCount} checkout request.`);
  }
  return { scanned: expiredContracts.length, created: createdCount };
};

export const startContractExpiryCheckoutJob = () => {
  let running = false;

  const run = async () => {
    if (running) return;
    running = true;
    try {
      await processExpiredContracts();
    } catch (error) {
      console.error('[CheckoutExpiry] Job thất bại:', error.message);
    } finally {
      running = false;
    }
  };

  // Chạy một lần ngay khi backend khởi động, sau đó kiểm tra mỗi giờ.
  void run();
  const timer = setInterval(run, CHECK_INTERVAL_MS);
  timer.unref?.();

  return () => clearInterval(timer);
};
